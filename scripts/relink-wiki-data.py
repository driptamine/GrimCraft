#!/usr/bin/env python3
"""Point wiki data links at local React pages instead of warhammer-guide.ru.

- Guardsmen_Squad.html -> /settings/wiki/guardsmen_squad/
- Any slug with a local data module -> /settings/wiki/article/?page=<slug>
- Everything else (images, anchors, unknown pages) stays untouched.

Usage: python3 scripts/relink-wiki-data.py
"""
import json
import os
import re

BASE = 'https://warhammer-guide.ru/wiki/'
DATA_RE = re.compile(r'= (\{.*\});\s*$', re.S)


def local_slugs():
    out = set()
    d = 'src/wiki/articles'
    if os.path.isdir(d):
        for f in os.listdir(d):
            if f.endswith('Data.ts'):
                out.add(f[:-len('Data.ts')])
    return out


def rewrite_link(href, local, lower):
    m = re.match(r"^/settings/wiki/article/\?page=([A-Za-z0-9_.\-']+)(#.*)?$", href)
    if m:
        slug, frag = m.group(1), m.group(2) or ''
        base = slug if slug in local else lower.get(slug.lower(), '')
        if slug == 'Guardsmen_Squad':
            return '/settings/wiki/guardsmen_squad/' + frag
        if base:
            return f'/settings/wiki/{base}/' + frag
        return href
    if href.startswith(BASE):
        rest = href[len(BASE):]
    elif re.match(r"^[A-Za-z0-9_.\-']+\.html(#[^#]*)?$", href):
        rest = href
    else:
        return href
    if '/' in rest:
        return href
    if '#' in rest:
        page, frag = rest.split('#', 1)
        frag = '#' + frag
    else:
        page, frag = rest, ''
    if not page.endswith('.html'):
        return href
    slug = page[:-len('.html')]
    if slug == 'Guardsmen_Squad':
        return '/settings/wiki/guardsmen_squad/' + frag
    base = slug if slug in local else lower.get(slug.lower(), '')
    if base:
        return f'/settings/wiki/{base}/' + frag
    return href


def rewrite_node(node, local, lower):
    if isinstance(node, dict):
        if 'link' in node and isinstance(node['link'], str):
            node['link'] = rewrite_link(node['link'], local, lower)
        if 'href' in node and isinstance(node['href'], str):
            node['href'] = rewrite_link(node['href'], local, lower)
        for v in node.values():
            if isinstance(v, (dict, list)):
                rewrite_node(v, local, lower)
    elif isinstance(node, list):
        for v in node:
            rewrite_node(v, local, lower)


def process(path, local, lower):
    h = open(path).read()
    m = DATA_RE.search(h)
    data = json.loads(m.group(1))
    rewrite_node(data, local, lower)
    head = h[:m.start(1)]
    new = head + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    open(path, 'w').write(new)


def write_manifest():
    import glob as _glob
    mapping = {}
    for f in sorted(_glob.glob('src/wiki/articles/*Data.ts')):
        base = f.split('/')[-1][:-len('Data.ts')]
        mapping.setdefault(base.lower(), base)
    lines = ['// Auto-generated by scripts/relink-wiki-data.py — do not edit by hand.',
             'export const wikiArticleFiles: Record<string, string> = {']
    for k in sorted(mapping):
        lines.append(f'  {json.dumps(k)}: {json.dumps(mapping[k])},')
    lines.append('};')
    open('src/wiki/articles/manifest.ts', 'w').write('\n'.join(lines) + '\n')
    return mapping


def main():
    local = local_slugs()
    print(f'local articles: {len(local)}')
    lower = {}
    for s in local:
        lower.setdefault(s.lower(), s)
    targets = ['src/wiki/guardsmenSquadData.ts']
    targets += [f'src/wiki/articles/{s}Data.ts' for s in sorted(local)]
    changed = 0
    for path in targets:
        before = open(path).read()
        process(path, local, lower)
        if open(path).read() != before:
            changed += 1
    print(f'rewrote links in {changed}/{len(targets)} files')
    mapping = write_manifest()
    print(f'manifest entries: {len(mapping)}')


if __name__ == '__main__':
    main()
